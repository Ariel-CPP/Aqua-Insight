// ===========================
// Core i18n Functions
// ===========================
function getLang() {
  return localStorage.getItem("aqua-insight-lang") || "id";
}

function setLang(lang) {
  localStorage.setItem("aqua-insight-lang", lang);
  document.documentElement.setAttribute("lang", lang);
  window.dispatchEvent(new Event('languageChanged'));
}

function t(key) {
  const lang = getLang();
  const dict = window.AQUA_I18N;
  if (dict[lang] && dict[lang][key] !== undefined) return dict[lang][key];
  if (dict["id"] && dict["id"][key] !== undefined) return dict["id"][key];
  return key; // fallback: return the key itself
}

window.AQUA_GET_LANG = getLang;
window.AQUA_SET_LANG = setLang;
window.AQUA_T = t;

// Apply language attribute on load
document.documentElement.setAttribute("lang", getLang());
