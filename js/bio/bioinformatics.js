  // --- Core WorkFlow Runner ---
  window.runPhylogenyWorkflow = function() {
    const text = document.getElementById('seqs-input').value.trim();
    if (!text) {
      alert("Masukkan minimal 2 sekuens FASTA terlebih dahulu.");
      return;
    }
    
    const parsed = parseUserSequenceFormat(text);
    if (parsed.length < 2) {
      alert("Format sekuens tidak dikenali atau jumlah sekuens kurang dari 2. Pastikan sekuens menggunakan format FASTA (>Nama_Sekuens) atau format MEGA/BioEdit (Nama ö Sekuens).");
      return;
    }
    
    const match = parseInt(document.getElementById('score-match').value);
    const mismatch = parseInt(document.getElementById('score-mismatch').value);
    const gap = parseInt(document.getElementById('score-gap').value);
    const method = document.getElementById('align-method').value;
    const model = document.getElementById('distance-model').value;
    const bootstrapReplicates = parseInt(document.getElementById('bootstrap-count').value);
    
    const prealignedCheck = document.getElementById('use-prealigned');
    const isPrealigned = prealignedCheck && prealignedCheck.classList.contains('active') && (prealignedCheck.parentElement.parentElement.style.display !== 'none');
    
    let msaSeqs = [];
    
    if (isPrealigned) {
      // Check length compatibility
      const len = parsed[0].seq.length;
      const valid = parsed.every(s => s.seq.length === len);
      if (!valid) {
        alert("Kesalahan: Panjang sekuens ter-align tidak sama! Nonaktifkan 'Gunakan Alignment yang Ada' untuk menyelaraskan ulang.");
        return;
      }
      msaSeqs = parsed.map(s => s.seq);
    } else {
      // Run Selected MSA
      if (method === 'upgma') {
        msaSeqs = progressiveUPGMAMSA(parsed, match, mismatch, gap);
      } else if (method === 'star') {
        msaSeqs = centerStarMSA(parsed, match, mismatch, gap);
      } else {
        // Pairwise
        const res = needlemanWunsch(parsed[0].seq, parsed[1].seq, match, mismatch, gap);
        msaSeqs = [res.align1, res.align2];
        parsed.splice(2); // Keep only top 2
      }
    }
    
    // Build Aligned Sequences list
    alignedSequences = parsed.map((s, idx) => ({
      id: s.id,
      seq: msaSeqs[idx]
    }));
    
    // Step 1: Alignment length and stats
    const alignLen = alignedSequences[0].seq.length;
    let conservedCount = 0;
    
    for (let c = 0; c < alignLen; c++) {
      let isConserved = true;
      let firstBase = alignedSequences[0].seq[c];
      if (firstBase === '-') isConserved = false;
      else {
        for (let s = 1; s < alignedSequences.length; s++) {
          if (alignedSequences[s].seq[c] !== firstBase) {
            isConserved = false;
            break;
          }
        }
      }
      if (isConserved) conservedCount++;
    }
    
    // Step 2: Avg pairwise identity
    let totalPairs = 0;
    let totalIdentity = 0;
    for (let i = 0; i < alignedSequences.length; i++) {
      for (let j = i + 1; j < alignedSequences.length; j++) {
        let matches = 0;
        let validSites = 0;
        for (let c = 0; c < alignLen; c++) {
          let b1 = alignedSequences[i].seq[c];
          let b2 = alignedSequences[j].seq[c];
          if (b1 === '-' && b2 === '-') continue;
          validSites++;
          if (b1 === b2) matches++;
        }
        if (validSites > 0) {
          totalIdentity += (matches / validSites);
          totalPairs++;
        }
      }
    }
    const avgIdentity = totalPairs > 0 ? (totalIdentity / totalPairs) * 100 : 0;
    
    // Display alignment output in colored pre
    let outputHTML = "";
    alignedSequences.forEach(s => {
      let coloredSeq = "";
      for (let char of s.seq) {
        if (char === 'A') coloredSeq += `<span class="base-a">${char}</span>`;
        else if (char === 'T') coloredSeq += `<span class="base-t">${char}</span>`;
        else if (char === 'C') coloredSeq += `<span class="base-c">${char}</span>`;
        else if (char === 'G') coloredSeq += `<span class="base-g">${char}</span>`;
        else coloredSeq += `<span class="base-gap">${char}</span>`;
      }
      
      // Pad ID to line alignment up
      let paddedId = s.id.substring(0, 25).padEnd(26, ' ');
      outputHTML += `${paddedId} ö  ${coloredSeq}\n`;
    });
    
    document.getElementById('alignment-output').innerHTML = outputHTML;
    document.getElementById('res-length').innerText = `${alignLen} bp`;
    document.getElementById('res-conserved').innerText = conservedCount;
    document.getElementById('res-identity').innerText = avgIdentity.toFixed(1) + "%";
    
    // Step 3: Build Phylogenetic Tree
    distanceMatrix = calculateDistanceMatrix(alignedSequences, model);
    const namesList = alignedSequences.map(s => s.id);
    phyloTree = constructNJTree(distanceMatrix, namesList);
    
    // Calculate Log-Likelihood of tree under Jukes-Cantor
    const logLik = computeTreeLikelihood(phyloTree, alignedSequences);
    document.getElementById('res-likelihood').innerText = logLik.toFixed(2);
    
    // Step 4: Run Bootstrapping
    if (bootstrapReplicates > 0) {
      runBootstrapSignificance(phyloTree, alignedSequences, model, bootstrapReplicates);
    }
    
    // Step 5: Render tree
    redrawPhyloCanvas();
    
    // Step 6: Build molecular report
    generateMolecularReport(alignedSequences, phyloTree);
    
    // Switch active view tab to tree
    switchBioTab('tree-tab', document.querySelectorAll('.tab-btn')[1]);
  };

